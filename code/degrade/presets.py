"""The three severity levels (mild, medium, heavy) for each medium, in one place.

Every script that makes synthetic pictures or sweeps severity reads these numbers, so "medium haze" means the
same thing everywhere. A preset only lists the settings that change; everything else keeps the model's default.
"""

PRESETS = {
    "haze": {
        "mild":   {"beta": 0.5},
        "medium": {"beta": 1.2},
        "heavy":  {"beta": 2.4},
    },
    "water": {
        "mild":   {"beta_red": 0.45, "beta_green": 0.18, "beta_blue": 0.08},
        "medium": {"beta_red": 0.90, "beta_green": 0.35, "beta_blue": 0.15},
        "heavy":  {"beta_red": 1.60, "beta_green": 0.65, "beta_blue": 0.30},
    },
    "glass": {
        "mild":   {"veil": 0.15, "smudge": 0.15, "droplets": 8},
        "medium": {"veil": 0.35, "smudge": 0.30, "droplets": 25},
        "heavy":  {"veil": 0.60, "smudge": 0.50, "droplets": 60},
    },
    "plastic": {
        "mild":   {"transmission": 0.88, "blur": 0.003},
        "medium": {"transmission": 0.70, "blur": 0.006},
        "heavy":  {"transmission": 0.45, "blur": 0.012},
    },
}

LEVELS = ("mild", "medium", "heavy")


def _calibrated():
    """PRESETS with haze and glass replaced by the settings Stage 2d fitted to the real pictures (configs/calibrated_presets.json).

    Haze: scene-depth fog with the fitted density and the fitted (dimmer) airlight. Glass: raindrops only (no veil, no smudge).
    Water and plastic have no real data to calibrate on, so they keep their original settings. Generated by tune_models.py; the
    file's "structure" key only records which variant won and is not a model setting.
    """
    import json
    from pathlib import Path

    fitted = json.loads((Path(__file__).resolve().parents[2] / "configs" / "calibrated_presets.json").read_text())
    presets = {medium: dict(levels) for medium, levels in PRESETS.items()}
    for medium in ("haze", "glass"):
        presets[medium] = {level: {k: v for k, v in settings.items() if k != "structure"} for level, settings in fitted[medium].items()}
    for level in LEVELS:
        presets["glass"][level] = {"veil": 0.0, "smudge": 0.0, **presets["glass"][level]}
    return presets


CALIBRATED_PRESETS = _calibrated()
# PRESETS above stays the ORIGINAL set (the model-validation scripts compare it with real data); pick a set by name here.
PRESET_SETS = {"original": PRESETS, "calibrated": CALIBRATED_PRESETS}


def active_name():
    """Which set the experiment scripts use: environment variable DIP_PRESETS = original (default) or calibrated."""
    import os

    name = os.environ.get("DIP_PRESETS", "original")
    if name not in PRESET_SETS:
        raise ValueError(f"DIP_PRESETS must be one of {sorted(PRESET_SETS)}, not {name!r}")
    return name


def active_presets():
    return PRESET_SETS[active_name()]


def severity_params(medium, factor):
    """Settings for a severity that is `factor` times the medium preset (factor 1 = the medium preset, 2 = twice as strong).

    Used by the severity sweep to ask how each restoration method copes as the degradation grows continuously.
    """
    if active_name() == "calibrated" and medium in ("haze", "glass"):
        medium_settings = CALIBRATED_PRESETS[medium]["medium"]
        if medium == "haze":
            return {**medium_settings, "beta": medium_settings["beta"] * factor}
        return {**medium_settings, "droplets": round(medium_settings["droplets"] * factor)}
    if medium == "haze":
        return {"beta": 1.2 * factor}
    if medium == "water":
        return {"beta_red": 0.9 * factor, "beta_green": 0.35 * factor, "beta_blue": 0.15 * factor}
    if medium == "glass":
        return {"veil": min(0.95, 0.35 * factor), "smudge": min(0.95, 0.30 * factor), "droplets": round(25 * factor)}
    if medium == "plastic":
        return {"transmission": max(0.05, 1.0 - 0.30 * factor), "blur": 0.006 * factor}
    raise ValueError(medium)
